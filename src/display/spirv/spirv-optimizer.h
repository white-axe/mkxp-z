#ifndef SPIRV_OPTIMIZER_H
#define SPIRV_OPTIMIZER_H

#include <cstddef>
#include <cstdint>
#include <string>
#include <vector>

class SpirvOptimizer
{
private:
    void *optimizer;
    void *optimizer_options;

public:
    enum Type
    {
        // Legalizes SPIR-V bytecode generated by a HLSL compiler such as DXC or Glslang.
        // That is, if you don't pass SPIR-V code generated by a HLSL compiler through this optimizer, the SPIR-V code might be invalid.
        LEGALIZATION,
        // Optimizes SPIR-V bytecode for performance.
        PERFORMANCE,
    };

    SpirvOptimizer(Type type);
    ~SpirvOptimizer();
    SpirvOptimizer(const SpirvOptimizer &other) = delete;
    SpirvOptimizer(SpirvOptimizer &&other) noexcept;
    SpirvOptimizer &operator=(const SpirvOptimizer &other) = delete;
    SpirvOptimizer &operator=(SpirvOptimizer &&other) noexcept;

    /*
     * Optimizes SPIR-V bytecode.
     *
     * You must check the validity of the input SPIR-V module yourself before passing it to this function; it's undefined behavior to pass an invalid SPIR-V module to this function.
     *
     * spirv_input: Pointer to the input SPIR-V bytecode.
     * spirv_input_size: Length of the input SPIR-V bytecode in 32-bit words.
     * spirv_output: If optimization is successful, this will be set to the optimized SPIR-V output. Otherwise this will be unchanged.
     * error_message: If optimization is successful, this will be unchanged. Otherwise, this will be set to a string containing the error that occurred.
     *
     * Return value: `true` if optimization was successful, otherwise `false`.
     */
    bool transform(
        const uint32_t *spirv_input,
        size_t spirv_input_size,
        std::vector<uint32_t> &spirv_output,
        std::string &error_message
    );
};

#endif // SPIRV_OPTIMIZER_H
