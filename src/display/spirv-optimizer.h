#ifndef SPIRV_OPTIMIZER_H
#define SPIRV_OPTIMIZER_H

#include <cstddef>
#include <cstdint>
#include <vector>

class SpirvOptimizer
{
private:
    void *optimizer;
    void *validator_options;
    void *optimizer_options;

public:
    enum Target
    {
        // SPIR-V 1.0, the maximum supported SPIR-V version in Vulkan 1.0 and OpenGL
        SPIRV_1_0,
        // SPIR-V 1.1
        SPIRV_1_1,
        // SPIR-V 1.2
        SPIRV_1_2,
        // SPIR-V 1.3, the maximum supported SPIR-V version in Vulkan 1.1 if the VK_KHR_spirv_1_4 Vulkan extension is unsupported
        SPIRV_1_3,
        // SPIR-V 1.4, the maximum supported SPIR-V version in Vulkan 1.1 if the VK_KHR_spirv_1_4 Vulkan extension is supported
        SPIRV_1_4,
        // SPIR-V 1.5, the maximum supported SPIR-V version in Vulkan 1.2
        SPIRV_1_5,
        // SPIR-V 1.6, the maximum supported SPIR-V version in Vulkan 1.3 and Vulkan 1.4
        SPIRV_1_6,
    };

    SpirvOptimizer(Target target);
    ~SpirvOptimizer();
    SpirvOptimizer(const SpirvOptimizer &other) = delete;
    SpirvOptimizer(SpirvOptimizer &&other) noexcept;
    SpirvOptimizer &operator=(const SpirvOptimizer &other) = delete;
    SpirvOptimizer &operator=(SpirvOptimizer &&other) noexcept;

    /*
     * Optimizes SPIR-V bytecode.
     * Also legalizes SPIR-V bytecode generated by a HLSL compiler such as DXC or Glslang; that is, if you don't pass SPIR-V code generated by a HLSL compiler through this optimizer, the SPIR-V code might be invalid.
     *
     * spirv_output: If optimization is successful, this will be set to the optimized SPIR-V output. Otherwise this will be unchanged.
     * spirv_input: Pointer to the input SPIR-V bytecode.
     * spirv_input_size: Length of the input SPIR-V bytecode in bytes.
     *
     * Return value: `true` if optimization was successful, otherwise `false`.
     */
    bool optimize(std::vector<uint8_t> &spirv_output, const uint8_t *spirv_input, size_t spirv_input_size);
};

#endif // SPIRV_OPTIMIZER_H
